function panelQcTsv() {
  const r = rng(20260104);
  const rows = ["target\tregion\tmean_depth\tpct_bases_20x\tpct_bases_50x\tusability"];
  for (const gene of GENES) {
    const depth = between(r, 24, 480);
    const p20 = Math.min(99.6, depth * 0.42 + 8 + r() * 4).toFixed(1);
    const p50 = Math.min(99.0, depth * 0.24 + 4 + r() * 3).toFixed(1);
    const usable = depth > 60 && Number(p50) > 80 ? "PASS" : "REVIEW";
    rows.push(
      [gene.name, `${gene.chrom}:${gene.start}-${gene.end}`, String(depth), p20, p50, usable].join("\t"),
    );
  }
  return rows.join("\n") + "\n";
}


function snvVcf(seed: number, count: number) {
  const r = rng(seed);
  const sigs = ["Pathogenic", "Likely_pathogenic", "VUS", "Likely_benign", "Benign"] as const;
  const rows: string[] = [];
  for (let i = 0; i < count; i++) {
    const gene = pick(r, GENES);
    const pos = between(r, gene.start, gene.end);
    const ref = pick(r, BASES);
    const alt = BASES.filter((b) => b !== ref)[between(r, 0, 2)];
    const dp = between(r, 12, 240);
    const af = (r() * 0.5 + 0.5).toFixed(3);
    const sig = pick(r, sigs);
    const filter = r() > 0.85 ? "LowQual" : "PASS";
    const ad = `${between(r, Math.floor(dp / 3), dp - 1)},${Math.max(1, dp - between(r, 1, Math.floor(dp / 2)))}`;
    const id =
      sig === "VUS" || sig === "Likely_benign" || sig === "Benign" ? "." : `SYN${between(r, 1000, 9999)}`;
    rows.push(
      [
        gene.chrom,
        pos,
        id,
        ref,
        alt,
        (r() * 900 + 60).toFixed(1),
        filter,
        `DP=${dp};AF=${af};CLNSIG=${sig}`,
        "GT:DP:AD",
        `${r() > 0.85 ? "0/1" : "1/1"}:${dp}:${ad}`,
      ].join("\t"),
    );
  }
  return rows.join("\n");
}

function svVcf() {
  const r = rng(20260102);
  const types = ["DEL", "DUP", "INV"] as const;
  const rows: string[] = [];
  for (let i = 0; i < 24; i++) {
    const gene = pick(r, GENES);
    const pos = between(r, gene.start, gene.start + 20000);
    const end = pos + between(r, 800, 240000);
    const type = pick(r, types);
    const info = `SVTYPE=${type};END=${end};SVLEN=${end - pos};AF=${r().toFixed(2)}`;
    rows.push(
      [gene.chrom, pos, "SYN_SV_" + (i + 1), "N", `<${type}>`, ".", "PASS", info, "GT", "0/1"].join("\t"),
    );
  }
  return rows.join("\n");
}

